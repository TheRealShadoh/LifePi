#!/usr/bin/env python3
"""Build LifePi as an installable, offline phone/tablet app (a PWA) with pygbag.

    pip install pygbag pygame-ce
    python web/build.py            # -> build/web/  (static files: host anywhere with HTTPS)
    python web/build.py --serve    # ...and serve it on http://localhost:8000 to try it

The game is the same lifepi.py, compiled to WebAssembly. On a phone: open the hosted page,
then "Add to Home Screen" (iPhone: Share menu; Android: browser menu / install prompt).
After the first visit it works offline.
"""
import argparse
import http.server
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAGE = ROOT / "build" / "web-src" / "lifepi"
OUT = ROOT / "build" / "web"
THEME = "#121218"


def make_icons(folder):
    """App icons drawn with pygame: four seats around a life total."""
    os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
    import pygame
    pygame.display.init()
    pygame.font.init()
    colours = [(46, 78, 140), (150, 42, 42), (38, 108, 62), (176, 150, 84)]

    def icon(size, pad):
        s = pygame.Surface((size, size))
        s.fill((18, 18, 24))
        inner = size - 2 * pad
        gap = max(2, inner // 40)
        half = (inner - gap) // 2
        for k, c in enumerate(colours):
            r = pygame.Rect(pad + (k % 2) * (half + gap), pad + (k // 2) * (half + gap), half, half)
            pygame.draw.rect(s, c, r, border_radius=max(3, inner // 10))
        rad = inner // 4
        centre = (size // 2, size // 2)
        pygame.draw.circle(s, (18, 18, 24), centre, rad + gap * 2)
        pygame.draw.circle(s, (240, 240, 246), centre, rad, max(2, size // 64))
        f = pygame.font.Font(None, int(rad * 1.25))
        t = f.render("40", True, (255, 255, 255))
        s.blit(t, t.get_rect(center=(centre[0], centre[1] + size // 90)))
        return s

    folder.mkdir(parents=True, exist_ok=True)
    for name, size, pad in (("favicon.png", 64, 2), ("icon-192.png", 192, 10), ("icon-512.png", 512, 26),
                            ("apple-touch-icon.png", 180, 12), ("icon-maskable-512.png", 512, 96)):
        pygame.image.save(icon(size, pad), str(folder / name))


MANIFEST = {
    "name": "LifePi - MTG life counter",
    "short_name": "LifePi",
    "description": "Touch-first Magic: The Gathering life counter for the whole table.",
    "start_url": "./",
    "scope": "./",
    "display": "fullscreen",
    "display_override": ["fullscreen", "standalone"],
    "orientation": "any",
    "background_color": THEME,
    "theme_color": THEME,
    "icons": [
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
        {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

# Offline: the app shell (this site) is network-first so updates arrive, falling back to the
# cache offline; everything else (pygbag's WebAssembly runtime on its CDN, card art) is
# cache-first. Scryfall API answers are never cached here - the app caches those itself.
SERVICE_WORKER = """// LifePi offline cache - generated by web/build.py
const CACHE = "lifepi-%(version)s";
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(%(shell)s)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.hostname === "api.scryfall.com") return;
  const store = (res) => {
    if (res && (res.ok || res.type === "opaque")) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  };
  if (url.origin === self.location.origin) {
    e.respondWith(fetch(req).then(store).catch(() => caches.match(req, { ignoreSearch: true })));
  } else {
    e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then(store)));
  }
});
"""

HEAD_TAGS = """
<link rel="manifest" href="manifest.webmanifest">
<meta name="theme-color" content="%(theme)s">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="LifePi">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<style>
  html, body { background: %(theme)s !important; overscroll-behavior: none; touch-action: none; }
  /* LifePi always draws at the page's own shape, so the canvas simply covers the viewport -
     also after the phone is turned (pygbag only sizes it once, at start) */
  #canvas { position: fixed !important; left: 0 !important; top: 0 !important; margin: 0 !important;
            width: 100vw !important; height: 100vh !important; height: 100dvh !important; }
</style>
<script>
  if ("serviceWorker" in navigator) addEventListener("load", () => navigator.serviceWorker.register("sw.js"));
  // pygbag asks "Leave site?" on every reload/close; LifePi saves continuously, so never ask.
  (function () {
    const add = window.addEventListener;
    window.addEventListener = function (type, ...rest) { if (type !== "beforeunload") return add.call(this, type, ...rest); };
    Object.defineProperty(window, "onbeforeunload", { configurable: true, get() { return null; }, set(v) {} });
  })();
</script>
""" % {"theme": THEME}


def build():
    if STAGE.parent.exists():
        shutil.rmtree(STAGE.parent)
    STAGE.mkdir(parents=True)
    shutil.copy(ROOT / "lifepi.py", STAGE / "lifepi.py")
    shutil.copy(ROOT / "web" / "main.py", STAGE / "main.py")
    make_icons(STAGE)
    subprocess.run([sys.executable, "-m", "pygbag", "--build", "--ume_block", "0", "--title", "LifePi",
                    "--package", "org.lifepi.web", "--icon", "favicon.png", str(STAGE)], check=True)
    built = STAGE / "build" / "web"
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.iterdir():                 # empty it in place (a running --serve keeps working)
        shutil.rmtree(old) if old.is_dir() else old.unlink()
    shutil.copytree(built, OUT, dirs_exist_ok=True)
    for name in ("favicon.png", "icon-192.png", "icon-512.png", "icon-maskable-512.png", "apple-touch-icon.png"):
        shutil.copy(STAGE / name, OUT / name)

    index = OUT / "index.html"
    html = index.read_text(encoding="utf-8")
    html = re.sub(r"(<head[^>]*>)", lambda m: m.group(1) + HEAD_TAGS, html, count=1, flags=re.I)
    html = re.sub(r'<meta name="viewport"[^>]*>',
                  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, '
                  'user-scalable=no, viewport-fit=cover">', html, count=1, flags=re.I)
    index.write_text(html, encoding="utf-8")
    (OUT / "manifest.webmanifest").write_text(json.dumps(MANIFEST, indent=1), encoding="utf-8")
    shell = ["./", "index.html", "manifest.webmanifest", "favicon.png", "icon-192.png", "icon-512.png",
             "apple-touch-icon.png"] + [f.name for f in OUT.glob("*.apk")]
    (OUT / "sw.js").write_text(SERVICE_WORKER % {"version": int(time.time()), "shell": json.dumps(shell)},
                               encoding="utf-8")
    (OUT / ".nojekyll").write_text("")        # GitHub Pages: serve files as they are
    print(f"\nBuilt {OUT}  ({sum(f.stat().st_size for f in OUT.rglob('*') if f.is_file()) // 1024} KB)")


def serve(port):
    os.chdir(OUT)

    class Handler(http.server.SimpleHTTPRequestHandler):
        extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map,
                          ".webmanifest": "application/manifest+json", ".apk": "application/octet-stream",
                          ".wasm": "application/wasm"}

        def end_headers(self):
            self.send_header("Cache-Control", "no-cache")
            super().end_headers()

    print(f"Serving http://localhost:{port}  (Ctrl+C to stop)")
    http.server.ThreadingHTTPServer(("", port), Handler).serve_forever()


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--serve", action="store_true", help="serve build/web on localhost after building")
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--no-build", action="store_true", help="just serve the last build")
    a = ap.parse_args()
    if not a.no_build:
        build()
    if a.serve or a.no_build:
        serve(a.port)
